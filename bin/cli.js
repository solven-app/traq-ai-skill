#!/usr/bin/env node
'use strict';

const readline = require('readline');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const https = require('https');
const http = require('http');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise((resolve) => rl.question(q, resolve));
const bold = (s) => `\x1b[1m${s}\x1b[0m`;
const cyan = (s) => `\x1b[36m${s}\x1b[0m`;
const green = (s) => `\x1b[32m${s}\x1b[0m`;
const yellow = (s) => `\x1b[33m${s}\x1b[0m`;
const red = (s) => `\x1b[31m${s}\x1b[0m`;

function httpGet(url) {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith('https') ? https : http;
    lib.get(url, (res) => {
      let data = '';
      res.on('data', c => data += c);
      res.on('end', () => resolve({ status: res.statusCode, body: data }));
    }).on('error', reject);
  });
}

async function main() {
  console.log('\n' + cyan('╔══════════════════════════════════════╗'));
  console.log(cyan('║') + bold('   🔥  TRAQ AI Skill Installer  🔥   ') + cyan('║'));
  console.log(cyan('╚══════════════════════════════════════╝') + '\n');
  console.log('This wizard will configure your AI agent to communicate with TRAQ.\n');

  // Step 1: Where is TRAQ?
  console.log(bold('Step 1: Where is TRAQ installed?'));
  console.log('  1) It\'s running locally on this machine');
  console.log('  2) It\'s hosted externally (domain/VPS/cloud)');
  console.log('  3) Not installed — install it now\n');

  const choice = await ask('Enter choice [1/2/3]: ');

  let baseUrl = '';

  if (choice.trim() === '3') {
    // Clone TRAQ
    console.log('\n' + yellow('📦 Cloning TRAQ from GitHub...'));
    const installDir = await ask('Enter install directory (default: ./traq): ') || './traq';
    try {
      execSync(`git clone https://github.com/solven-app/traq.git ${installDir}`, { stdio: 'inherit' });
      console.log(green('\n✅ TRAQ cloned successfully!'));
      console.log(yellow('\n⚡ To start TRAQ, run:'));
      console.log(`   cd ${installDir} && npm install && npm run dev`);
      console.log('\nThen re-run this installer after the server is running.\n');
      rl.close();
      return;
    } catch (e) {
      console.log(red('\n❌ Git clone failed. Make sure git is installed and you have internet access.'));
      rl.close();
      return;
    }
  } else if (choice.trim() === '1') {
    const port = await ask('Which port is TRAQ running on? (default: 3001): ') || '3001';
    baseUrl = `http://localhost:${port.trim()}`;
  } else if (choice.trim() === '2') {
    baseUrl = await ask('Enter your TRAQ domain (e.g. https://traq.yourdomain.com): ');
    baseUrl = baseUrl.trim().replace(/\/$/, '');
  } else {
    console.log(red('Invalid choice.'));
    rl.close();
    return;
  }

  // Step 2: Verify connectivity
  console.log('\n' + yellow(`🔌 Testing connection to ${baseUrl}...`));
  try {
    const result = await httpGet(`${baseUrl}/api/users/exists`);
    if (result.status === 200) {
      console.log(green('✅ Connection successful!'));
    } else {
      console.log(yellow(`⚠️  Server responded with status ${result.status}. Continuing anyway.`));
    }
  } catch (e) {
    console.log(red(`❌ Could not connect to ${baseUrl}. Is the server running?`));
    const cont = await ask('Continue anyway? [y/N]: ');
    if (cont.toLowerCase() !== 'y') { rl.close(); return; }
  }

  // Step 3: API Key
  console.log('\n' + bold('Step 2: API Key Configuration'));
  console.log('Your AI agent needs an API key to authenticate with TRAQ.');
  console.log('To generate one:');
  console.log(`  1. Open TRAQ in your browser at ${baseUrl}`);
  console.log('  2. Go to Settings → API Management');
  console.log('  3. Click "Generate Key", then copy the key shown (it\'s only displayed once!)');
  console.log('  4. Activate the key in the UI and enable the permissions you need.\n');

  const apiKey = await ask('Paste your TRAQ API key here: ');
  if (!apiKey.trim().startsWith('traq_')) {
    console.log(yellow('⚠️  Warning: TRAQ keys usually start with "traq_". Double-check the key.'));
  }

  // Step 4: Write .env file
  const envPath = path.resolve(process.cwd(), '.env');
  const envContent = [
    '# TRAQ AI Skill Configuration',
    `# Generated by traq-ai-skill installer on ${new Date().toISOString()}`,
    '',
    `TRAQ_API_URL=${baseUrl}`,
    `TRAQ_API_KEY=${apiKey.trim()}`,
  ].join('\n');

  let overwrite = 'y';
  if (fs.existsSync(envPath)) {
    overwrite = await ask(`\n⚠️  .env already exists at ${envPath}. Overwrite? [y/N]: `);
  }

  if (overwrite.toLowerCase() === 'y' || !fs.existsSync(envPath)) {
    fs.writeFileSync(envPath, envContent + '\n', 'utf8');
    console.log(green(`\n✅ .env written to ${envPath}`));
  } else {
    console.log(yellow('\n⚠️  Skipped writing .env. You can manually add:'));
    console.log(cyan(`  TRAQ_API_URL=${baseUrl}`));
    console.log(cyan(`  TRAQ_API_KEY=${apiKey.trim()}`));
  }

  // Step 5: Copy SKILL.md
  const skillSrc = path.join(__dirname, '..', 'SKILL.md');
  const skillDest = path.resolve(process.cwd(), 'TRAQ_SKILL.md');
  if (fs.existsSync(skillSrc)) {
    fs.copyFileSync(skillSrc, skillDest);
    console.log(green(`📄 SKILL.md copied to ${skillDest}`));
  }

  console.log('\n' + cyan('╔══════════════════════════════════════╗'));
  console.log(cyan('║') + bold('   ✅  Setup Complete!               ') + cyan('║'));
  console.log(cyan('╚══════════════════════════════════════╝'));
  console.log(`
${bold('Your AI can now use TRAQ via:')}
  Base URL : ${cyan(baseUrl)}
  Auth     : ${cyan('Authorization: Bearer <your-key>')}

${bold('Point your AI to:')} ${green(skillDest)}
for the full endpoint reference.
`);
  rl.close();
}

main().catch((e) => {
  console.error(red('\n❌ Installer error:'), e.message);
  process.exit(1);
});
